// Generate from the pinned runtime and explicit config only; never from an operator's dotenv/secrets.
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
const require = createRequire(import.meta.url), root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'src/worker-configuration.d.ts');
const check = process.argv.slice(2).includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check'))
    throw new Error('Usage: generate-worker-types.mjs [--check]');
const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'beedle-worker-types-'));
try {
    const config = JSON.parse(await fs.readFile(path.join(root, 'wrangler.json'), 'utf8'));
    config.main = path.resolve(root, config.main);
    delete config.$schema;
    for (const env of [config, ...Object.values(config.env || {})])
        for (const db of env.d1_databases || [])
            if (db.migrations_dir)
                db.migrations_dir = path.resolve(root, db.migrations_dir);
    await fs.writeFile(path.join(temp, '.dev.vars'), '');
    await fs.writeFile(path.join(temp, '.env'), '');
    const configPath = path.join(temp, 'wrangler.json');
    await fs.writeFile(configPath, JSON.stringify(config));
    // The output lives next to the checked-in destination so relative mainModule imports are stable.
    const generated = path.join(root, 'src/.worker-configuration.generated-' + randomUUID() + '.d.ts');
    const env = {
        CI: '1', PATH: process.env.PATH, WRANGLER_SEND_METRICS: 'false', WRANGLER_LOG_PATH: path.join(temp, 'wrangler.log')
    };
    const child = spawn(process.execPath, [require.resolve('wrangler'), 'types', generated, '--config', configPath, '--env-interface', 'WorkerBindings', '--strict-vars', 'false'], { cwd: temp, env, stdio: ['ignore', 'pipe', 'pipe'] });
    let logs = '';
    for (const stream of [child.stdout, child.stderr])
        stream.on('data', bytes => {
            logs = (logs + bytes).slice(-20000);
        });
    const timer = setTimeout(() => child.kill('SIGKILL'), 60000);
    let code;
    try {
        code = await new Promise((resolve, reject) => {
            child.once('error', reject);
            child.once('exit', resolve);
        });
    }
    finally {
        clearTimeout(timer);
    }
    try {
        if (code !== 0)
            throw new Error('Pinned Wrangler type generation failed: ' + logs);
        const raw = await fs.readFile(generated, 'utf8');
        const content = raw.replace(/^\/\/ Generated by Wrangler.*$/m, '// Generated by the pinned Wrangler via pnpm --filter @beedle/api types:generate. Do not edit.').replace(/[ \t]+$/gm, '');
        if (check) {
            if (await fs.readFile(output, 'utf8').catch(error => {
                if (error.code === 'ENOENT')
                    return '';
                throw error;
            }) !== content)
                throw new Error('Worker binding/runtime types are stale. Run pnpm --filter @beedle/api types:generate.');
        }
        else
            await fs.writeFile(output, content);
    }
    finally {
        await fs.rm(generated, { force: true });
    }
    console.log(check ? 'Worker binding/runtime types match the explicit config.' : 'Generated Worker binding/runtime types.');
}
finally {
    await fs.rm(temp, { recursive: true, force: true });
}
