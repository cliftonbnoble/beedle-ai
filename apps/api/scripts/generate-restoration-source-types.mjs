// Keep operator dotenv/credentials out of the empty restoration source's generated types.
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url),root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const check=process.argv.slice(2).includes('--check');
if(process.argv.slice(2).some(arg=>arg!=='--check'))throw Error('Usage: generate-restoration-source-types.mjs [--check]');
const temp=await fs.mkdtemp(path.join(os.tmpdir(),'beedle-restoration-source-types-'));
try{
 const config=JSON.parse(await fs.readFile(path.join(root,'restoration-source.wrangler.json'),'utf8'));delete config.$schema;config.main=path.resolve(root,config.main);
 await fs.writeFile(path.join(temp,'.dev.vars'),'');await fs.writeFile(path.join(temp,'.env'),'');await fs.writeFile(path.join(temp,'wrangler.json'),JSON.stringify(config));
 const child=spawn(process.execPath,[require.resolve('wrangler'),'types',path.join(temp,'bindings.d.ts'),'--config',path.join(temp,'wrangler.json'),'--env-interface','RestorationSourceBindings','--strict-vars','false','--include-runtime','false'],{cwd:temp,env:{CI:'1',PATH:process.env.PATH,WRANGLER_SEND_METRICS:'false',WRANGLER_LOG_PATH:path.join(temp,'wrangler.log')},stdio:['ignore','pipe','pipe']});
 let logs='';for(const stream of [child.stdout,child.stderr])stream.on('data',bytes=>{logs=(logs+bytes).slice(-16000);});
 const timeout=setTimeout(()=>child.kill('SIGKILL'),60000);let code;
 try{code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',resolve);});}finally{clearTimeout(timeout);}
 if(code!==0)throw Error('Restoration source type generation failed: '+logs);
 const generated=await fs.readFile(path.join(temp,'bindings.d.ts'),'utf8');
 // Only primitive vars, one D1 and the three explicit R2 bindings are configured. Avoid a second global
 // Cloudflare mainModule/runtime augmentation alongside the application types.
 const declaration=generated.match(/interface Env\s*\{[\s\S]*?\n\s*\}/)?.[0]?.replace('interface Env','interface RestorationSourceBindings');
 if(!declaration)throw Error('Generated restoration source binding declaration missing');
 const output=path.join(root,'src/restoration-source-configuration.d.ts');
 const content='// Generated by the pinned Wrangler via node scripts/generate-restoration-source-types.mjs. Do not edit.\n'+declaration.replace(/[ \t]+$/gm,'')+'\n';
 if(check){if(await fs.readFile(output,'utf8')!==content)throw Error('Restoration source bindings are stale');}
 else await fs.writeFile(output,content);
 console.log(check?'Restoration source binding types match.':'Generated restoration source binding types.');
}finally{await fs.rm(temp,{recursive:true,force:true});}
